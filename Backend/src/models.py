class SessionData(BaseModel):
    """
    Stores relevant information regarding the session, including messages, configuration,
    client instances, API keys, and uploaded files.

    Attributes:
        session_id: The session's internal ID.
        chats: All the chat histories associated with the session.
        config: Configuration dictionary, one sub-dict for each method.
        uploaded_files: Dictionary storing each uploaded PDF file.
        scheduled_tasks: LLM queries scheduled for later execution by Internal Tools.
        last_scheduled_task_id: Last assigned scheduled task ID, used to generate monotonic IDs.
        notifications_chats_map: Which notifications should be auto-appended to which chats.
        valid_until: Timestamp until session is active.
        mcp_servers: All added mcp server information in JSON format.
        blocked: Whether this session is currently blocked, not accepting any requests.
        prompts: Prompt Library data.
        play_books: User-defined play books exposed through internal tools.
        is_notifs_aborted: Boolean indicating if all current notification generations should be aborted.
    Transient fields:
        _websocket: Can be used to send intermediate result and other messages back to the UI
        _ws_message_queue: Used to buffer messages received from the websocket
        _ws_out_cache: Used to cache outgoing WS messages if WS is disconnected, to be sent later
        _opaca_client: Client instance for OPACA, for calling agent actions.
        _llm_clients: Dictionary of LLM client instances.
        _user_api_keys: User-provided API keys for specific LLM hosts

    Note: The websocket from the session should not be used directly; instead use the send/receive
    methods. Especially the latter is necessary to ensure that messages are properly received while
    the server is using the same method for waiting for the webserver to be closed again.
    """
    session_id: str = Field(default_factory=lambda: str(uuid.uuid4()), alias='_id')
    user_id: str = Field(default="")
    original_session_id: str = Field(default="")
    chats: Dict[str, Chat] = Field(default_factory=dict)
    config: Dict[str, Any] = Field(default_factory=dict)
    uploaded_files: Dict[str, OpacaFile] = Field(default_factory=dict)
    scheduled_tasks: Dict[int, ScheduledTask] = Field(default_factory=dict)
    last_scheduled_task_id: int = -1
    notifications_chats_map: Dict[int, Set[str]] = Field(default_factory=dict)
    valid_until: float = -1
    mcp_servers: Dict[str, MCPServer] = Field(default_factory=dict)
    opaca_approvals: Dict[str, Dict[str, ToolApprovalState]] = Field(default_factory=dict)
    blocked: bool = False
    prompts: SessionPrompts | None = None
    play_books: List[PlayBook] = Field(default_factory=list)
    is_notifs_aborted: bool = False

    _websocket: WebSocket | None = PrivateAttr(default=None)
    _ws_msg_queue: asyncio.Queue | None = PrivateAttr(default=None)
    _ws_out_cache: list[dict] | None = PrivateAttr(default_factory=list)
    _opaca_client: OpacaClient = PrivateAttr(default_factory=OpacaClient)
    _user_api_keys: Dict[str, str] = PrivateAttr(default_factory=dict)

    @model_validator(mode="after")
    def initialize_scheduled_task_id_counter(self) -> "SessionData":
        task_ids = [self.last_scheduled_task_id]
        task_ids.extend(int(task_id) for task_id in self.scheduled_tasks)
        self.last_scheduled_task_id = max(task_ids)
        return self

    def create_scheduled_task_id(self) -> int:
        self.last_scheduled_task_id += 1
        return self.last_scheduled_task_id

    def enabled_play_books(self) -> List[PlayBook]:
        return [play_book for play_book in self.play_books if play_book.enabled]

    def set_play_book(self, play_book: PlayBook) -> None:
        for index, current_play_book in enumerate(self.play_books):
            if current_play_book.id == play_book.id:
                self.play_books[index] = play_book
                return
        self.play_books.append(play_book)

    def delete_play_book(self, play_book_id: str) -> bool:
        for index, play_book in enumerate(self.play_books):
            if play_book.id == play_book_id:
                self.play_books.pop(index)
                return True
        return False

    @property
    def opaca_client(self) -> OpacaClient:
        return self._opaca_client

    def is_valid(self) -> bool:
        return self.valid_until > time.time()

    def create_user_session(self, user_id: str) -> "SessionData":
        """
        Creates a new user session instance based on the current anonymous session.
        """
        user_session = SessionData(**self.model_dump(exclude={"session_id"}))
        user_session._websocket = self._websocket
        user_session._ws_msg_queue = self._ws_msg_queue
        user_session._ws_out_cache = self._ws_out_cache
        user_session._opaca_client = self._opaca_client
        user_session._user_api_keys = copy.deepcopy(self._user_api_keys)
        user_session.user_id = user_id
        user_session.original_session_id = self.session_id
        # Set "valid_until" to year 2100 to avoid deletion of the user session
        user_session.valid_until = datetime(2100, 1, 1).timestamp()
        return user_session

    def get_config(self, method) -> 'MethodConfig':
        config = self.config.get(method.NAME, method.CONFIG())
        if isinstance(config, dict):  # config is deserialized from DB as dict since the exact type is not known then
            try:
                config = method.CONFIG.model_validate(config, extra='forbid')
            except ValidationError as e:
                logger.warning(f"Config does not comply with schema; resetting to default.")
                config = method.CONFIG()
        self.config[method.NAME] = config
        return self.config[method.NAME]

    def get_or_create_chat(self, chat_id: str, create_if_missing: bool = False) -> Chat:
        chat = self.chats.get(chat_id)
        if chat is None and create_if_missing:
            chat = Chat(chat_id=chat_id)
            self.chats[chat_id] = chat
        elif chat is None and not create_if_missing:
            raise KeyError(f"Chat {chat_id} not found")
        return chat

    def delete_chat(self, chat_id: str) -> bool:
        if chat_id in self.chats:
            del self.chats[chat_id]
            return True
        return False

    def set_api_key(self, model: str, api_key: str):
        self._user_api_keys[model.rsplit("/", 1)[0]] = api_key

    def get_api_key(self, model: str) -> str | None:
        return self._user_api_keys.get(model.rsplit("/", 1)[0], None)

    def has_websocket(self) -> bool:
        return self._websocket is not None

    async def websocket_send_pending(self):
        for msg in self._ws_out_cache:
            await self._websocket.send_json(msg)
        self._ws_out_cache.clear()

    async def websocket_send(self, message: BaseModel) -> str:
        """Send object as JSON over websocket. The JSON will include the class name as "type", as well
        as a UUID "id". The id is returned and can be used to retrieve a response to the message."""
        id = str(uuid.uuid4())
        typed_message = {
            "type": message.__class__.__name__,
            "id": id,
            **message.model_dump()
        }
        if self._websocket:
            await self._websocket.send_json(typed_message)
        else:
            self._ws_out_cache.append(typed_message)
        return id

    async def websocket_receive(self, id: str) -> dict:
        if self._websocket and self._ws_msg_queue:
            while True:
                msg = await self._ws_msg_queue.get()
                if msg["id"] == id:
                    return msg
                else:
                    await self._ws_msg_queue.put(msg)  # not the message we are looking for
                    await asyncio.sleep(0.1)  # wait a bit before checking the queue again
        else:
            raise Exception("Websocket not connected")

    def get_mcp_tools(self) -> dict[str, list[MCPTool]]:
        """Returns a list of all available mcp server tools."""
        return {
            server.server_label: list(server.tools.values())
            for server in self.mcp_servers.values()
        }

    def get_mcp_tool(self, server_label: str, tool_name: str) -> MCPTool:
        full_name = f"{server_label}--{tool_name}"
        if not (server := self.mcp_servers.get(server_label)):
            raise KeyError(f"MCP server with label '{server_label}' not found.")
        if not (tool := server.tools.get(full_name)):
            raise KeyError(f"Tool '{full_name}' not found in MCP server '{server_label}'.")
        return tool

    def set_mcp_tool_approval(self, server_label: str, tool_name: str, approval: ToolApprovalState):
        """Set whether a tool call should be allowed, denied, or require confirmation by the user."""
        tool = self.get_mcp_tool(server_label, tool_name)
        tool.approval = approval

    def get_opaca_tool_approval(self, tool_name: str) -> ToolApprovalState:
        """Returns the approval state for a given OPACA/internal tool the user has set. It does not check the admin blacklist."""
        for container_approvals in self.opaca_approvals.values():
            if tool_name in container_approvals:
                return container_approvals[tool_name]
        return ToolApprovalState.ALLOW

    def set_opaca_tool_approval(self, container_id: str, tool_name: str, approval: ToolApprovalState):
        if container_id not in self.opaca_approvals:
            self.opaca_approvals[container_id] = {}
        self.opaca_approvals[container_id][tool_name] = approval

    async def add_mcp_server(self, req: MCPCreateRequest) -> bool:
        """Adds a new mcp server json"""

        # Check if the server url is in a valid format:
        if not re.match(r'^https?://', req.server_url):
            raise OpacaException("The 'server_url' needs to be in a valid url-format (e.g. 'http://<address>.com/mcp')", "Malformed 'server_url'!", 400)

        # Check if a previous mcp server with the same url already exists
        if any(m.server_url == req.server_url for m in self.mcp_servers.values()):
            raise OpacaException(f"An MCP server with the given server_url '{req.server_url}' already exists!", "Duplicate 'server_url'!", 400)

        # If no server label was given, transform the server_url into the label
        if not req.server_label:
            req.server_label = re.sub(r'^.*//([^/]+).*$', r'\1', req.server_url).replace('.', '-')

        # Check if a previous mcp server with the same label already exists (UI saves mcp servers based on label)
        if req.server_label in self.mcp_servers:
            raise OpacaException(f"An MCP server with the given server_label '{req.server_label}' already exists!", "Duplicate 'server_label'!", 400)

        # Check if the given server-url is actually an mcp server
        client = MCPClient(server_url=req.server_url)
        client_tools = await client.list_tools()
        if not client_tools:
            raise OpacaException(f"The given server_url '{req.server_url}' provides no mcp tools and cannot be added!", "Unreachable MCP server!", 400)

        mcp_tools = {
            f"{req.server_label}--{tool.name}": MCPTool(
                name=tool.name,
                description=tool.description or '',
                inputSchema=tool.inputSchema,
                server_label=req.server_label,
                approval=req.default_approval
            )
            for tool in client_tools
        }
        self.mcp_servers[req.server_label] = MCPServer(
            server_url=req.server_url,
            server_label=req.server_label,
            type=req.type,
            tools=mcp_tools
        )
        return True

    def delete_mcp_server(self, mcp_name: str) -> bool:
        """Deletes an mcp server based on its name. The UI only stores the server_label."""
        if mcp_name in self.mcp_servers:
            del self.mcp_servers[mcp_name]
            return True
        return False

    def prune_notifications_chats_map(self):
        """Remove orphaned taskIds and invalid chatIds."""
        to_delete = []

        for task_id, chat_ids in list(self.notifications_chats_map.items()):
            # Delete map entries for tasks no longer scheduled
            if task_id not in self.scheduled_tasks:
                to_delete.append(task_id)
                continue

            # Remove chat_ids that no longer exist
            if cleaned := {cid for cid in chat_ids if cid in self.chats}:
                self.notifications_chats_map[task_id] = cleaned
            else:
                to_delete.append(task_id)

        # Remove any empty / invalid entries
        for task_id in to_delete:
            del self.notifications_chats_map[task_id]


